export function getExaminersForCompany(
  companyNameOrPt: string,
  configs: CompanyExaminerConfig[] = initialExaminerConfigs,
  doctors: Doctor[] = initialDoctors
): CompanyExaminerConfig {
  const query = (companyNameOrPt || '').trim().toLowerCase();
  const matched = configs.find((c) => {
    const cName = c.companyName.trim().toLowerCase();
    return cName === query || (query && cName.includes(query)) || (query && query.includes(cName));
  });

  if (matched) return matched;

  // Fallback to default config
  const defaultConfig = configs.find((c) => c.companyName.toLowerCase().includes('default')) || configs[0];
  if (defaultConfig) return defaultConfig;

  return {
    id: 0,
    companyName: companyNameOrPt || 'Default',
    koordinatorMcu: doctors.find((d) => d.spesialis.toLowerCase().includes('okupasi'))?.nama || doctors[0]?.nama || 'dr. Hendra Wijaya, Sp.Ok',
    pemeriksaFisik: doctors.find((d) => d.spesialis.toLowerCase().includes('umum') || d.spesialis.toLowerCase().includes('pemeriksa'))?.nama || 'dr. Anisa Rahmawati',
    dokterRadiologi: doctors.find((d) => d.spesialis.toLowerCase().includes('radiologi'))?.nama || 'dr. Farida Hanum, Sp.Rad',
    dokterPatologiKlinik: doctors.find((d) => d.spesialis.toLowerCase().includes('patologi'))?.nama || 'dr. Kevin Hendrawan, Sp.PK',
    dokterSpesialisTht: doctors.find((d) => d.spesialis.toLowerCase().includes('tht'))?.nama || 'dr. Bambang Hermanto, Sp.THT-BKL',
    dokterSpesialisParu: doctors.find((d) => d.spesialis.toLowerCase().includes('paru'))?.nama || 'dr. Rina Setyowati, Sp.P, FAPSR',
    dokterSpesialisOkupasi: doctors.find((d) => d.spesialis.toLowerCase().includes('okupasi'))?.nama || 'dr. Budi Santoso, Sp.Ok',
  };
}

